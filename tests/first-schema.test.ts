import { expect, test } from '@playwright/test';

// "Your first schema" runs the playground's editor (comline-web-kit) and its
// compiler: the starting schema compiles to Rust and TypeScript, and a typo
// in it is reported instead.
test('first schema: compiles, switches language, and reports a mistake', async ({ page }) => {
	await page.goto('/part-2_basics/sect-1_your-first-schema/');

	const lesson = page.locator('.schema-editor');
	await expect(lesson.locator('.cm-content')).toContainText('protocol Greeter');

	await lesson.getByRole('button', { name: 'Compile' }).click();
	await expect(lesson.locator('.status.ok')).toBeVisible({ timeout: 30_000 });
	await expect(lesson.locator('.code.out .cm-content')).toContainText('Generated by Comline');

	await lesson.getByRole('combobox').selectOption('typescript');
	await expect(lesson.locator('.status.ok')).toBeVisible();
	// (CodeMirror only renders the lines in view, so this looks near the top.)
	await expect(lesson.locator('.code.out .cm-content')).toContainText('interface Person');

	// Misspell the field's type.
	await lesson
		.locator('.code:not(.out) .cm-line', { hasText: /^\s*name: string$/ })
		.click();
	await page.keyboard.press('End');
	await page.keyboard.type('g');
	await lesson.getByRole('button', { name: 'Compile' }).click();
	await expect(lesson.locator('.status.err')).toContainText('stringg');
});
